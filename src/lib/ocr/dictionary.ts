/**
 * 단어 원형 및 파생형(형용사, 부사, 복수형, 과거형, 진행형)에 대한 영한 사전 뜻 고정밀 탐색
 */
export function lookupWordMeaning(rawWord: string): DictEntry | null {
  if (!rawWord) return null;
  const word = rawWord.trim().toLowerCase();

  // 1. 직접 매칭
  if (BUILTIN_DICTIONARY[word]) {
    return BUILTIN_DICTIONARY[word];
  }

  // 2. 파생형 변형 규칙 탐색 (부사 -ly, 복수형 -s/-es, 과거형 -ed, 진행형 -ing)
  const candidates: string[] = [];

  // 부사 -> 형용사/명사
  if (word.endsWith('ly')) {
    candidates.push(word.slice(0, -2)); // quickly -> quick
    if (word.endsWith('ily')) candidates.push(word.slice(0, -3) + 'y'); // happily -> happy
    if (word.endsWith('ally')) candidates.push(word.slice(0, -4)); // basically -> basic
  }

  // 진행형/동명사 -ing
  if (word.endsWith('ing')) {
    candidates.push(word.slice(0, -3)); // forming -> form
    candidates.push(word.slice(0, -3) + 'e'); // changing -> change
    if (word.endsWith('ting') || word.endsWith('ning') || word.endsWith('ping') || word.endsWith('ding') || word.endsWith('ming')) {
      candidates.push(word.slice(0, -4)); // running -> run, swimming -> swim
    }
  }

  // 과거형/과거분사 -ed
  if (word.endsWith('ed')) {
    candidates.push(word.slice(0, -2)); // formed -> form
    candidates.push(word.slice(0, -1)); // changed -> change
    if (word.endsWith('ied')) candidates.push(word.slice(0, -3) + 'y'); // studied -> study
    if (word.endsWith('ted') || word.endsWith('ned') || word.endsWith('ped') || word.endsWith('ded')) {
      candidates.push(word.slice(0, -3));
    }
  }

  // 3인칭 단수 및 복수형 -s, -es, -ies
  if (word.endsWith('ies')) candidates.push(word.slice(0, -3) + 'y'); // activities -> activity
  if (word.endsWith('es')) candidates.push(word.slice(0, -2)); // boxes -> box
  if (word.endsWith('s') && !word.endsWith('ss')) candidates.push(word.slice(0, -1)); // habits -> habit

  for (const cand of candidates) {
    if (BUILTIN_DICTIONARY[cand]) {
      const base = BUILTIN_DICTIONARY[cand];
      // 부사인 경우 뜻 자동 적응
      let meaning = base.meaning;
      if (word.endsWith('ly') && !cand.endsWith('ly')) {
        meaning = `${base.meaning} (부사 형태)`;
      }
      return {
        ...base,
        meaning: base.meaning,
      };
    }
  }

  return null;
}
